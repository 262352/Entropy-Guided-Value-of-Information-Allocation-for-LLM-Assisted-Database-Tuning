LABELS = {"ours": "Ours", "mctuner_official": "MCTuner", "gp_bo": "GP-BO",
          "smac": "SMAC", "ottertune": "OtterTune", "cdbtune": "CDBTune",
          "restune": "ResTune", "dot_official": "DOT"}
COLORS = dict(zip(LABELS, ["#d62728", "#ff7f0e", "#2ca02c", "#9467bd",
                          "#8c564b", "#e377c2", "#7f7f7f", "#1f77b4"]))
TITLES = {"twitter": "Twitter", "tpcc": "TPC-C", "ycsb": "YCSB",
          "chbenchmark": "CH-benCHmark"}


def build_curve(series):
    changes = {int(k): v for k, v in series["steps"].items()}
    values = []
    current = changes[1]
    for i in range(1, series["rounds"] + 1):
        current = changes.get(i, current)
        values.append(current)
    return list(range(1, len(values) + 1)), values


def main():
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 11,
                         "axes.labelsize": 12, "pdf.fonttype": 42, "ps.fonttype": 42})
    fig, axes = plt.subplots(2, 2, figsize=(14, 8.5))
    handles = {}
    for ax, workload in zip(axes.flat, TITLES):
        for method in LABELS:
            series = DATA[workload]["methods"].get(method)
            if series is None:
                continue
            x, y = build_curve(series)
            line, = ax.plot(x, y, label=LABELS[method], color=COLORS[method],
                            marker="o", markersize=4, markevery=10,
                            linewidth=2.6 if method in ("ours", "mctuner_official") else 1.9,
                            drawstyle="steps-post", alpha=.95)
            handles.setdefault(method, line)
        ax.set_xlim(1, 100)
        ax.xaxis.set_major_locator(MultipleLocator(20))
        ax.xaxis.set_minor_locator(MultipleLocator(10))
        ax.yaxis.set_major_formatter(PercentFormatter(xmax=1))
        ax.grid(which="major", linestyle="--", linewidth=.7, alpha=.55)
        ax.grid(which="minor", linestyle=":", linewidth=.5, alpha=.3)
        ax.axhline(0, color="gray", linewidth=.8, alpha=.6)
        ax.set_ylabel(r"Best throughput improvement $\Delta$")
        ax.set_xlabel(TITLES[workload] + " — configuration evaluations", labelpad=10)
    order = [method for method in LABELS if method in handles]
    fig.legend([handles[m] for m in order], [LABELS[m] for m in order],
               loc="lower center", bbox_to_anchor=(.5, .06), ncol=4,
               frameon=False, fontsize=12, columnspacing=1.5)
    fig.text(.5, .025, "Best-so-far throughput improvement over default",
             ha="center", fontsize=14)
    fig.subplots_adjust(bottom=.23, top=.97, wspace=.22, hspace=.36, left=.08, right=.98)
    output = Path(__file__).resolve().parent
    for extension in ("png", "pdf"):
        target = output / ("throughput_delta_2x2." + extension)
        fig.savefig(target, dpi=300, bbox_inches="tight")
        print(target)
    plt.close(fig)


if __name__ == "__main__":
    main()
